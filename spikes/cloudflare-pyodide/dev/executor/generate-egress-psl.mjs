// Generate identical policy data for the API image and the Worker bundle.
import {readFileSync, writeFileSync} from 'node:fs';
import {domainToASCII} from 'node:url';

if (process.argv.length !== 3) throw new Error('Usage: node generate-egress-psl.mjs public_suffix_list.dat');
const source = readFileSync(process.argv[2], 'utf8');
const version = source.match(/^\/\/ VERSION: (\S+)/m)?.[1];
const commit = source.match(/^\/\/ COMMIT: ([a-f0-9]{40})$/m)?.[1];
if (!version || !commit) throw new Error('Expected the versioned official Public Suffix List');

function rules(section) {
  const content = source.split(`// ===BEGIN ${section} DOMAINS===`)[1]?.split(`// ===END ${section} DOMAINS===`)[0];
  if (!content) throw new Error(`Missing ${section} section`);
  return content.split(/\r?\n/).map((line) => line.trim()).filter((line) => line && !line.startsWith('//'));
}

function asciiRule(rule) {
  const prefix = rule.match(/^(?:\*\.|!)/)?.[0] ?? '';
  const ascii = domainToASCII(rule.slice(prefix.length));
  if (!ascii) throw new Error(`Invalid Public Suffix List rule: ${rule}`);
  return prefix + ascii;
}

const icann = new Set(rules('ICANN').map(asciiRule));
const privateRoots = new Set();
for (const rule of rules('PRIVATE').map(asciiRule)) {
  const labels = rule.replace(/^\*\.|^!/, '').split('.');
  let suffixLength = 0;
  for (let index = 0; index < labels.length; index++) {
    const suffix = labels.slice(index).join('.');
    if (icann.has(`!${suffix}`)) {
      suffixLength = labels.length - index - 1;
      break;
    }
    if (icann.has(suffix) || icann.has(`*.${labels.slice(index + 1).join('.')}`)) {
      suffixLength = labels.length - index;
      break;
    }
  }
  if (suffixLength > 0 && labels.length > suffixLength) {
    privateRoots.add(labels.slice(-suffixLength - 1).join('.'));
  }
}

const license = 'Public Suffix List data, Mozilla Public License 2.0: https://mozilla.org/MPL/2.0/';
const files = [
  [new URL('../../../../api/src/services/execution/cloudflare_psl.json', import.meta.url), '', ''],
  [new URL('./egress-psl.generated.mjs', import.meta.url), '// Generated by generate-egress-psl.mjs.\nexport default ', ';'],
];
const header = {license, version, commit};
const data = [
  ...Object.entries(header).map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)}`),
  ...Object.entries({icann: [...icann].sort(), privateRoots: [...privateRoots].sort()}).map(([key, values]) => {
    const rows = [];
    for (let index = 0; index < values.length; index += 8) {
      rows.push(`    ${values.slice(index, index + 8).map((value) => JSON.stringify(value)).join(', ')}`);
    }
    return `  "${key}": [\n${rows.join(',\n')}\n  ]`;
  }),
].join(',\n');
for (const [path, prefix, suffix] of files) writeFileSync(path, `${prefix}{\n${data}\n}${suffix}\n`);
